"""'kdx agents sync': one AGENTS.md, every coding agent's rule file kept in step.

AGENTS.md is the open format most agents read (Codex, Jules, Zed, Aider, Amp, ...). Others
look elsewhere: Claude Code reads CLAUDE.md, Gemini CLI GEMINI.md, Cursor .cursor/rules/,
GitHub Copilot .github/copilot-instructions.md, Windsurf .windsurf/rules/, Cline
.clinerules/. Copies drift the day someone edits one of them, so this command writes them
all from AGENTS.md: an import line where the agent supports imports, a full copy where it
does not. ``--check`` fails when any of them is stale, which is what a CI step runs.

Every generated file carries a marker line. A file without it was written by a person and
is never overwritten unless ``--force`` says so.
"""

from __future__ import annotations

import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, cast

from ..constants import TAG_ERROR, TAG_NOTE, TAG_OK, ExitCode
from ..fsio import atomic_write_text
from ..kernel.cli_contract import CliArgument, CliCommand, CliRequest
from .render import dump_json, tr, write_line

if TYPE_CHECKING:
    from ..kernel.chassis import Chassis

SOURCE_NAME = "AGENTS.md"
MARKER = "generated by 'kdx agents sync' from AGENTS.md - edit AGENTS.md, then run it again"


@dataclass(frozen=True, slots=True)
class AgentTarget:
    """One agent's rule file and how it is rendered from AGENTS.md."""

    key: str
    label: str
    path: str
    render: Callable[[str], str]


def _import_file(title: str) -> Callable[[str], str]:
    """Render a file that imports AGENTS.md ('@AGENTS.md'), so it never goes stale."""

    def render(_source: str) -> str:
        return "\n".join(
            [
                f"<!-- {MARKER} -->",
                f"# {title}",
                "",
                "The project rules live in AGENTS.md; this file only imports them.",
                "",
                f"@{SOURCE_NAME}",
                "",
            ]
        )

    return render


def _copy(source: str) -> str:
    return f"<!-- {MARKER} -->\n{source.rstrip()}\n"


def _cursor(source: str) -> str:
    return "\n".join(
        [
            "---",
            "description: Project rules for AI agents (from AGENTS.md)",
            "globs:",
            "alwaysApply: true",
            "---",
            f"<!-- {MARKER} -->",
            source.rstrip(),
            "",
        ]
    )


def _windsurf(source: str) -> str:
    return "\n".join(
        ["---", "trigger: always_on", "---", f"<!-- {MARKER} -->", source.rstrip(), ""]
    )


TARGETS: tuple[AgentTarget, ...] = (
    AgentTarget("claude", "Claude Code", "CLAUDE.md", _import_file("CLAUDE.md")),
    AgentTarget("gemini", "Gemini CLI", "GEMINI.md", _import_file("GEMINI.md")),
    AgentTarget("cursor", "Cursor", ".cursor/rules/agents.mdc", _cursor),
    AgentTarget("copilot", "GitHub Copilot", ".github/copilot-instructions.md", _copy),
    AgentTarget("windsurf", "Windsurf", ".windsurf/rules/agents.md", _windsurf),
    AgentTarget("cline", "Cline", ".clinerules/agents.md", _copy),
)
"""Agents that do not read AGENTS.md on their own, and where their rules go."""

NATIVE_READERS = ("Codex", "Jules", "Zed", "Aider", "Amp", "opencode", "Devin", "Factory")
"""Agents that read AGENTS.md directly and need no file of their own."""


@dataclass(frozen=True, slots=True)
class SyncRow:
    """What syncing one target found or did."""

    key: str
    path: str
    state: str
    """'written', 'current', 'stale', 'missing', or 'kept' (a hand-written file)."""

    def as_dict(self) -> dict[str, str]:
        return {"agent": self.key, "path": self.path, "state": self.state}


def sync_agents(
    root: Path,
    *,
    only: tuple[str, ...] = (),
    check: bool = False,
    force: bool = False,
) -> list[SyncRow]:
    """Write (or, with *check*, compare) every agent file under *root* from AGENTS.md."""
    source = (root / SOURCE_NAME).read_text(encoding="utf-8")
    rows: list[SyncRow] = []
    for target in TARGETS:
        if only and target.key not in only:
            continue
        path = root / target.path
        wanted = target.render(source)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == wanted:
            rows.append(SyncRow(target.key, target.path, "current"))
            continue
        hand_written = current is not None and MARKER not in current
        if check:
            state = "missing" if current is None else ("kept" if hand_written else "stale")
            rows.append(SyncRow(target.key, target.path, state))
            continue
        if hand_written and not force:
            rows.append(SyncRow(target.key, target.path, "kept"))
            continue
        atomic_write_text(path, wanted)
        rows.append(SyncRow(target.key, target.path, "written"))
    return rows


def agents_command() -> CliCommand:
    """Return the 'kdx agents' group."""
    return CliCommand(
        name="agents",
        help="Keep every AI agent's rule file in step with AGENTS.md.",
        group="core",
        remote=False,
        subcommands=(
            CliCommand(
                name="sync",
                help="Write CLAUDE.md, GEMINI.md, Cursor, Copilot, Windsurf and Cline rules "
                "from AGENTS.md.",
                group="core",
                handler=_sync,
                remote=False,
                args=(
                    CliArgument(
                        ("--check",), dest="check", action="store_true",
                        help="Change nothing; exit 1 when a file is missing or stale (for CI).",
                    ),
                    CliArgument(
                        ("--force",), dest="force", action="store_true",
                        help="Also overwrite a rule file a person wrote.",
                    ),
                    CliArgument(
                        ("--only",), dest="only", metavar="AGENTS",
                        help="Comma-separated subset: " + ", ".join(t.key for t in TARGETS) + ".",
                    ),
                    CliArgument(
                        ("--json",), dest="as_json", action="store_true", help="Emit JSON.",
                    ),
                ),
            ),
        ),
    )


def _sync(request: CliRequest) -> int:
    chassis = cast("Chassis", request.options.get("chassis") or request.context.chassis)
    root = Path(chassis.paths.root)
    only = tuple(
        item.strip() for item in str(request.option("only") or "").split(",") if item.strip()
    )
    unknown = [item for item in only if item not in {target.key for target in TARGETS}]
    if unknown:
        write_line(
            f"{TAG_ERROR} " + tr("unknown agent: {names}", names=", ".join(unknown)),
            stream=sys.stderr,
        )
        return int(ExitCode.USAGE_ERROR)
    if not (root / SOURCE_NAME).is_file():
        write_line(
            f"{TAG_ERROR} " + tr("{path} not found", path=root / SOURCE_NAME), stream=sys.stderr
        )
        write_line(f"{TAG_NOTE} " + tr("write AGENTS.md first ('kdx init' seeds one)"))
        return int(ExitCode.ERROR)
    check = request.flag("check")
    rows = sync_agents(root, only=only, check=check, force=request.flag("force"))
    failing = [row for row in rows if row.state in ("missing", "stale")]
    if request.flag("as_json"):
        dump_json({"rows": [row.as_dict() for row in rows], "native": list(NATIVE_READERS)})
    else:
        tags = {"written": TAG_OK, "current": TAG_OK, "kept": TAG_NOTE}
        labels = {
            "written": tr("written"),
            "current": tr("up to date"),
            "kept": tr("kept (written by a person)"),
            "stale": tr("stale"),
            "missing": tr("missing"),
        }
        for row in rows:
            label = labels.get(row.state, row.state)
            write_line(f"{tags.get(row.state, TAG_ERROR)} {row.path}: {label}")
        if any(row.state == "kept" for row in rows):
            write_line(f"{TAG_NOTE} " + tr("a file a person wrote is kept; --force replaces it"))
        write_line(
            f"{TAG_NOTE} "
            + tr("these read AGENTS.md directly: {names}", names=", ".join(NATIVE_READERS))
        )
    return int(ExitCode.ERROR if check and failing else ExitCode.SUCCESS)
