"""``kdx ui types``: TypeScript route types generated from a daemon's ``GET /api/v1/schema``.

Conventions section 16 says client types come from the contract. The contract lists every route
(method, auth, role, owning module) and, for the core's own routes, the top-level fields of the
answer. This writes them as one TypeScript module: a ``RoutePath`` union, a ``ROUTES`` table,
the documented fields, and ``route()``, which only accepts a path the daemon serves. An app that
names its routes through ``route("/api/v1/...")`` fails its type check when a route disappears,
instead of failing on the person's screen. The output is deterministic (sorted, no timestamps),
so ``--check`` can tell a stale file in CI.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from typing import Any

HEADER = (
    "// Generated by 'kdx ui types' from GET /api/v1/schema. Do not edit: run it again after a\n"
    "// route changes ('kdx ui types --check' tells whether this file is stale).\n"
)


def _routes(contract: Mapping[str, Any]) -> dict[str, dict[str, Any]]:
    """Return path -> {methods, auth, role, module, fields}, core and module routes merged."""
    merged: dict[str, dict[str, Any]] = {}
    for item in [*contract.get("routes", []), *contract.get("module_routes", [])]:
        if not isinstance(item, Mapping) or not str(item.get("path") or "").startswith("/"):
            continue
        path = str(item["path"])
        methods = item.get("methods") or [item.get("method") or "GET"]
        entry = merged.setdefault(
            path,
            {"methods": set(), "auth": False, "role": "", "module": "", "fields": set()},
        )
        entry["methods"].update(str(method).upper() for method in methods)
        entry["auth"] = entry["auth"] or bool(item.get("auth"))
        entry["role"] = entry["role"] or str(item.get("role") or "")
        entry["module"] = entry["module"] or str(item.get("module") or "core")
        entry["fields"].update(str(name) for name in item.get("fields") or [])
    return merged


def _union(values: Iterable[str], sep: str = "\n  | ") -> str:
    items = [json.dumps(value) for value in sorted(set(values))]
    return sep.join(items) if items else "never"


def render_types(contract: Mapping[str, Any]) -> str:
    """Return the TypeScript module for *contract* (the JSON of ``GET /api/v1/schema``)."""
    routes = _routes(contract)
    mounts = [str(mount.get("route_prefix") or "") for mount in contract.get("static_mounts", [])]
    lines = [
        HEADER,
        f"export const SCHEMA_VERSION = {int(contract.get('schema') or 0)};",
        f"export const CORE_API = {int(contract.get('core_api') or 0)};",
        "",
        f"export type RoutePath =\n  | {_union(routes)};",
        "",
        f"export type StaticMount =\n  | {_union(mount for mount in mounts if mount)};",
        "",
        "export interface RouteInfo {",
        "  readonly methods: readonly string[];",
        "  readonly auth: boolean;",
        "  readonly role: string;",
        "  readonly module: string;",
        "}",
        "",
        "export const ROUTES = {",
    ]
    for path in sorted(routes):
        entry = routes[path]
        methods = ", ".join(json.dumps(method) for method in sorted(entry["methods"]))
        lines.append(
            f"  {json.dumps(path)}: {{ methods: [{methods}], auth: {str(entry['auth']).lower()}, "
            f"role: {json.dumps(entry['role'])}, module: {json.dumps(entry['module'])} }},"
        )
    lines.append("} as const satisfies Record<RoutePath, RouteInfo>;")
    return "\n".join([*lines, *_tail(routes)])


def _tail(routes: Mapping[str, dict[str, Any]]) -> list[str]:
    """Return the documented fields and the ``route()`` helper."""
    lines = ["", "/** Top-level fields the core documents for its own answers. */",
             "export interface RouteFields {"]
    for path in sorted(routes):
        if routes[path]["fields"]:
            lines.append(f"  {json.dumps(path)}: {_union(routes[path]['fields'], ' | ')};")
    return [
        *lines,
        "}",
        "",
        "/** A route this daemon serves; a removed route fails the type check where it is used. */",
        "export function route<P extends RoutePath>(path: P, query = \"\"): string {",
        "  return query ? `${path}?${query}` : path;",
        "}",
        "",
    ]


__all__ = ["HEADER", "render_types"]
