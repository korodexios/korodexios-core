"""Wiki pages on disk: parse, list, search, index and check them (no I/O beyond files).

A page is a Markdown file with a small YAML header::

    ---
    title: Deploying the daemon
    tags: [ops, install]
    summary: How the service is installed on a fresh host.
    updated: 2026-11-06
    ---
    # Deploying the daemon
    ...

Its language is the last suffix before ``.md``: ``deploy.en.md``, ``deploy.sk.md``,
``deploy.de.md`` are one page in three languages; a bare ``deploy.md`` is the default
language. Pages may sit in topic folders (``ops/deploy.en.md`` is the slug ``ops/deploy``).
``INDEX.md`` files are generated and never count as pages.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any, Final

import yaml

__all__ = [
    "INDEX_MARKER",
    "INDEX_NAME",
    "Issue",
    "Page",
    "check_pages",
    "page_file",
    "parse_page",
    "render_index",
    "render_page",
    "scan",
    "search",
    "valid_slug",
]

INDEX_NAME: Final[str] = "INDEX.md"
INDEX_MARKER: Final[str] = "<!-- generated by 'kdx wiki index'; edit the pages, not this file -->"
SLUG_PART: Final[re.Pattern[str]] = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")
LANGUAGE: Final[re.Pattern[str]] = re.compile(r"^[a-z]{2,3}(_[A-Z]{2})?$")
LINK: Final[re.Pattern[str]] = re.compile(r"\]\((?!https?://|mailto:|#)([^)\s#]+)(#[^)]*)?\)")
CODE: Final[re.Pattern[str]] = re.compile(r"```.*?```|`[^`\n]*`", re.DOTALL)
"""Fenced blocks and inline code: a link written there is an example, not a link."""
SNIPPETS: Final[int] = 3


@dataclass(frozen=True, slots=True)
class Page:
    """One language version of one page."""

    slug: str
    language: str
    scope: str
    path: Path
    title: str
    tags: tuple[str, ...] = ()
    summary: str = ""
    updated: str = ""
    body: str = ""
    problems: tuple[str, ...] = field(default=())

    def as_dict(self, *, body: bool = False) -> dict[str, Any]:
        data: dict[str, Any] = {
            "slug": self.slug,
            "language": self.language,
            "scope": self.scope,
            "path": str(self.path),
            "title": self.title,
            "tags": list(self.tags),
            "summary": self.summary,
            "updated": self.updated,
        }
        if body:
            data["body"] = self.body
        return data


@dataclass(frozen=True, slots=True)
class Issue:
    """One finding of 'kdx wiki check'."""

    severity: str
    path: str
    message: str

    def as_dict(self) -> dict[str, str]:
        return {"severity": self.severity, "path": self.path, "message": self.message}


def valid_slug(slug: str) -> bool:
    """Return True for 'deploy' or 'ops/deploy': lower-case parts, '-' and '_' allowed."""
    parts = str(slug).strip("/").split("/")
    return bool(parts) and len(parts) <= 3 and all(SLUG_PART.match(part) for part in parts)


def page_file(directory: Path, slug: str, language: str) -> Path:
    """Return where page *slug* in *language* lives under *directory*."""
    return directory / f"{slug}.{language}.md"


def _split_name(relative: Path, default_language: str) -> tuple[str, str]:
    stem = relative.name[: -len(".md")]
    head, dot, tail = stem.rpartition(".")
    language = tail if dot and LANGUAGE.match(tail) else default_language
    name = head if dot and LANGUAGE.match(tail) else stem
    slug = "/".join([*relative.parent.parts, name]) if relative.parent.parts else name
    return slug, language


def parse_page(path: Path, root: Path, scope: str, default_language: str) -> Page:
    """Read one page; a header that does not parse is a problem, not a crash."""
    text = path.read_text(encoding="utf-8")
    slug, language = _split_name(path.relative_to(root), default_language)
    header: dict[str, Any] = {}
    body = text
    problems: list[str] = []
    if text.startswith("---\n") or text.startswith("---\r\n"):
        end = text.find("\n---", 3)
        if end == -1:
            problems.append("the header has no closing '---'")
        else:
            try:
                loaded = yaml.safe_load(text[4:end]) or {}
            except yaml.YAMLError as exc:
                loaded = {}
                problems.append(f"the header is not YAML: {exc}")
            header = loaded if isinstance(loaded, dict) else {}
            body = text[end + 4 :].lstrip("\r\n")
    title = str(header.get("title") or "").strip()
    if not title:
        heading = next((line[2:].strip() for line in body.splitlines()
                        if line.startswith("# ")), "")
        title = heading or slug
        problems.append("no 'title' in the header")
    raw_tags = header.get("tags") or ()
    tags = tuple(str(tag) for tag in raw_tags) if isinstance(raw_tags, list | tuple) else (
        tuple(item.strip() for item in str(raw_tags).split(",") if item.strip())
    )
    return Page(
        slug=slug,
        language=language,
        scope=scope,
        path=path,
        title=title,
        tags=tags,
        summary=str(header.get("summary") or "").strip(),
        updated=str(header.get("updated") or ""),
        body=body,
        problems=tuple(problems),
    )


def scan(directory: Path, scope: str, default_language: str) -> list[Page]:
    """Return every page under *directory*, sorted by slug then language."""
    if not directory.is_dir():
        return []
    pages = [
        parse_page(path, directory, scope, default_language)
        for path in sorted(directory.rglob("*.md"))
        if not path.name.startswith(("INDEX.", INDEX_NAME)) and path.is_file()
    ]
    return sorted(pages, key=lambda page: (page.slug, page.language))


def render_page(title: str, *, tags: Sequence[str] = (), summary: str = "", body: str = "") -> str:
    """Return a new page with its header and a first heading."""
    header = {
        "title": title,
        "tags": list(tags),
        "summary": summary,
        "updated": date.today().isoformat(),
    }
    head = yaml.safe_dump(header, sort_keys=False, allow_unicode=True).strip()
    text = body.strip() or (
        "Write the page here. Link another page by its file name, for example `setup.en.md`."
    )
    return f"---\n{head}\n---\n# {title}\n\n{text}\n"


def search(pages: Iterable[Page], query: str) -> list[tuple[Page, int, list[str]]]:
    """Return (page, score, snippets) for pages holding every word of *query*, best first."""
    words = [word.lower() for word in str(query).split() if word.strip()]
    if not words:
        return []
    found: list[tuple[Page, int, list[str]]] = []
    for page in pages:
        title, tags = page.title.lower(), " ".join(page.tags).lower()
        haystack = " ".join([title, tags, page.summary.lower(), page.slug, page.body.lower()])
        if not all(word in haystack for word in words):
            continue
        score = sum(
            5 * (word in title) + 3 * (word in tags) + 2 * (word in page.summary.lower())
            + page.body.lower().count(word)
            for word in words
        )
        snippets = [
            line.strip()[:160]
            for line in page.body.splitlines()
            if any(word in line.lower() for word in words) and line.strip()
        ][:SNIPPETS]
        found.append((page, score, snippets))
    return sorted(found, key=lambda item: (-item[1], item[0].slug, item[0].language))


def render_index(
    pages: Sequence[Page], scope: str, languages: Sequence[str], directory: Path
) -> str:
    """Return INDEX.md for one scope: every page, its languages, tags and summary."""
    grouped: dict[str, list[Page]] = {}
    for page in pages:
        grouped.setdefault(page.slug, []).append(page)
    lines = [
        INDEX_MARKER,
        f"# Wiki index ({scope})",
        "",
        f"{len(grouped)} pages; languages configured: {', '.join(languages)}.",
        "",
        "| Page | Title | Languages | Tags | Summary |",
        "| --- | --- | --- | --- | --- |",
    ]
    for slug, versions in sorted(grouped.items()):
        first = versions[0]
        links = ", ".join(
            f"[{page.language}]({page.path.relative_to(directory).as_posix()})"
            for page in versions
        )
        lines.append(
            f"| `{slug}` | {first.title} | {links} | {', '.join(first.tags)} | {first.summary} |"
        )
    return "\n".join(lines) + "\n"


def check_pages(
    pages: Sequence[Page], languages: Sequence[str], *, index_current: bool = True,
) -> list[Issue]:
    """Return what is wrong: bad headers, broken links, missing translations, stale index."""
    issues: list[Issue] = []
    by_slug: dict[str, set[str]] = {}
    for page in pages:
        by_slug.setdefault(page.slug, set()).add(page.language)
        for problem in page.problems:
            issues.append(Issue("warning", str(page.path), problem))
        prose = CODE.sub("", page.body)
        for target, _anchor in LINK.findall(prose):
            if target.endswith(".md") and not (page.path.parent / target).resolve().exists():
                issues.append(Issue("error", str(page.path), f"broken link to {target}"))
    for slug, present in sorted(by_slug.items()):
        for language in languages:
            if language not in present:
                have = ", ".join(sorted(present))
                issues.append(Issue("warning", slug, f"no {language} version (only {have})"))
    if not index_current:
        issues.append(Issue("warning", INDEX_NAME, "the index is stale; run 'kdx wiki index'"))
    return issues
