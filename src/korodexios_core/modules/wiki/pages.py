"""Wiki pages on disk, in the LLM-wiki layout: parse, list, search, index, log and check.

The layout follows the LLM-wiki pattern (raw sources, an LLM-maintained wiki, a schema),
so a ``kdx wiki`` folder and an existing LLM-wiki or Obsidian vault can be merged or pointed
at each other::

    docs/wiki/
      SCHEMA.md            conventions for this wiki (written once, then owned by its users)
      index.md             generated catalog, grouped by page type, as [[wikilinks]]
      log.md               append-only: "## [YYYY-MM-DD] <op> | <description>"
      raw/                 immutable sources (articles, PDFs, transcripts, notes)
      sources/ entities/ concepts/ synthesis/ decisions/ guides/   pages by type
      deploy.md            a page in the default language
      deploy.sk.md         the same page in Slovak

A page is Markdown with a YAML header (``type``, ``title``, ``tags``, ``sources``,
``summary``, ``created``, ``updated``; a source page adds ``raw`` and ``ingested``). Its name
is the file name without ``.md`` and without the language suffix, so ``[[deploy]]`` links
it - Obsidian-style - from anywhere in the wiki.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any, Final

import yaml

__all__ = [
    "INDEX_MARKER",
    "INDEX_NAME",
    "LOG_NAME",
    "SCHEMA_NAME",
    "TYPE_DIRS",
    "Issue",
    "Page",
    "append_log",
    "check_pages",
    "dump_header",
    "page_path",
    "parse_page",
    "raw_files",
    "read_log",
    "render_index",
    "render_page",
    "scan",
    "schema_text",
    "search",
    "skipped_path",
    "valid_slug",
    "wikilinks",
]

INDEX_NAME: Final[str] = "index.md"
LOG_NAME: Final[str] = "log.md"
SCHEMA_NAME: Final[str] = "SCHEMA.md"
RAW_DIR: Final[str] = "raw"
INDEX_MARKER: Final[str] = "<!-- generated by 'kdx wiki index'; edit the pages, not this file -->"
NOT_PAGES: Final[frozenset[str]] = frozenset({"index.md", "log.md", "schema.md"})
SKIPPED_DIRS: Final[frozenset[str]] = frozenset({"raw", "graph", "assets"})
TYPE_DIRS: Final[dict[str, str]] = {
    "source": "sources",
    "entity": "entities",
    "concept": "concepts",
    "synthesis": "synthesis",
    "decision": "decisions",
    "guide": "guides",
}
"""Page types and their folders: the LLM-wiki four plus two a software project needs."""
SOURCED_TYPES: Final[frozenset[str]] = frozenset({"entity", "concept", "synthesis"})
"""Types whose pages must name the sources they draw from."""
ENTRY_NAMES: Final[frozenset[str]] = frozenset({"home", "readme", "start", "start-here"})
"""Pages a reader starts from; they need no inbound link."""
SLUG_PART: Final[re.Pattern[str]] = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")
LANGUAGE: Final[re.Pattern[str]] = re.compile(r"^[a-z]{2,3}(_[A-Z]{2})?$")
LINK: Final[re.Pattern[str]] = re.compile(r"\]\((?!https?://|mailto:|#)([^)\s#]+)(#[^)]*)?\)")
WIKILINK: Final[re.Pattern[str]] = re.compile(r"\[\[([^\]|#\n]+)(#[^\]|\n]*)?(\|[^\]\n]*)?\]\]")
CODE: Final[re.Pattern[str]] = re.compile(r"```.*?```|`[^`\n]*`", re.DOTALL)
"""Fenced blocks and inline code: a link written there is an example, not a link."""
LOG_ENTRY: Final[re.Pattern[str]] = re.compile(r"^## \[(\d{4}-\d{2}-\d{2})\] (\S+) \| (.*)$")
SNIPPETS: Final[int] = 3
SOFT_LINES: Final[int] = 400
HARD_LINES: Final[int] = 800


@dataclass(frozen=True, slots=True)
class Page:
    """One language version of one page."""

    slug: str
    language: str
    scope: str
    path: Path
    title: str
    name: str = ""
    """The wikilink name: the file name without '.md' and the language suffix."""
    type: str = ""
    tags: tuple[str, ...] = ()
    sources: tuple[str, ...] = ()
    summary: str = ""
    created: str = ""
    updated: str = ""
    raw: str = ""
    body: str = ""
    problems: tuple[str, ...] = field(default=())

    def as_dict(self, *, body: bool = False) -> dict[str, Any]:
        data: dict[str, Any] = {
            "slug": self.slug,
            "name": self.name or self.slug.rsplit("/", 1)[-1],
            "language": self.language,
            "scope": self.scope,
            "path": str(self.path),
            "type": self.type,
            "title": self.title,
            "tags": list(self.tags),
            "sources": list(self.sources),
            "summary": self.summary,
            "created": self.created,
            "updated": self.updated,
        }
        if self.raw:
            data["raw"] = self.raw
        if body:
            data["body"] = self.body
        return data


@dataclass(frozen=True, slots=True)
class Issue:
    """One finding of 'kdx wiki check'."""

    severity: str
    path: str
    message: str

    def as_dict(self) -> dict[str, str]:
        return {"severity": self.severity, "path": self.path, "message": self.message}


def valid_slug(slug: str) -> bool:
    """Return True for 'deploy' or 'ops/deploy': lower-case parts, '-' and '_' allowed."""
    parts = str(slug).strip("/").split("/")
    return bool(parts) and len(parts) <= 3 and all(SLUG_PART.match(part) for part in parts)


def page_path(
    directory: Path, slug: str, language: str, default_language: str, page_type: str = ""
) -> Path:
    """Return where page *slug* lives: in its type's folder, suffixed unless default language.

    ``deploy`` in the default language is ``deploy.md`` - the name ``[[deploy]]`` resolves to
    in any LLM-wiki or Obsidian tool; its Slovak version is ``deploy.sk.md``.
    """
    relative = slug
    folder = TYPE_DIRS.get(page_type)
    if folder and "/" not in slug:
        relative = f"{folder}/{slug}"
    suffix = "" if language == default_language else f".{language}"
    return directory / f"{relative}{suffix}.md"


def _split_name(relative: Path, default_language: str) -> tuple[str, str, str]:
    stem = relative.name[: -len(".md")]
    head, dot, tail = stem.rpartition(".")
    is_language = bool(dot) and bool(LANGUAGE.match(tail))
    language = tail if is_language else default_language
    name = head if is_language else stem
    slug = "/".join([*relative.parent.parts, name]) if relative.parent.parts else name
    return slug, name, language


def _header(text: str) -> tuple[dict[str, Any], str, list[str]]:
    if not (text.startswith("---\n") or text.startswith("---\r\n")):
        return {}, text, []
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text, ["the header has no closing '---'"]
    try:
        loaded = yaml.safe_load(text[4:end]) or {}
    except yaml.YAMLError as exc:
        return {}, text[end + 4 :].lstrip("\r\n"), [f"the header is not YAML: {exc}"]
    header = loaded if isinstance(loaded, dict) else {}
    return header, text[end + 4 :].lstrip("\r\n"), []


def _strings(value: Any) -> tuple[str, ...]:
    if isinstance(value, list | tuple):
        return tuple(str(item).strip() for item in value if str(item).strip())
    return tuple(item.strip() for item in str(value or "").split(",") if item.strip())


def parse_page(path: Path, root: Path, scope: str, default_language: str) -> Page:
    """Read one page; a header that does not parse is a problem, not a crash."""
    text = path.read_text(encoding="utf-8")
    slug, name, language = _split_name(path.relative_to(root), default_language)
    header, body, problems = _header(text)
    title = str(header.get("title") or "").strip()
    if not title:
        heading = next((line[2:].strip() for line in body.splitlines()
                        if line.startswith("# ")), "")
        title = heading or name
        problems.append("no 'title' in the header")
    return Page(
        slug=slug,
        name=name,
        language=language,
        scope=scope,
        path=path,
        title=title,
        type=str(header.get("type") or "").strip(),
        tags=_strings(header.get("tags")),
        sources=_strings(header.get("sources")),
        summary=str(header.get("summary") or "").strip(),
        created=str(header.get("created") or ""),
        updated=str(header.get("updated") or ""),
        raw=str(header.get("raw") or "").strip(),
        body=body,
        problems=tuple(problems),
    )


def skipped_path(relative: Path) -> bool:
    """Return True for what is not a page: raw/, graph/, dot folders, index, log, schema."""
    folders = relative.parts[:-1]
    if any(part in SKIPPED_DIRS or part.startswith(".") for part in folders):
        return True
    return relative.name.casefold() in NOT_PAGES


def scan(directory: Path, scope: str, default_language: str) -> list[Page]:
    """Return every page under *directory* (not raw/, graph/, index, log or schema)."""
    if not directory.is_dir():
        return []
    pages = [
        parse_page(path, directory, scope, default_language)
        for path in sorted(directory.rglob("*.md"))
        if path.is_file() and not skipped_path(path.relative_to(directory))
    ]
    return sorted(pages, key=lambda page: (page.slug, page.language))


def raw_files(directory: Path) -> list[str]:
    """Return the raw sources under *directory*/raw, as wiki-relative POSIX paths."""
    raw = directory / RAW_DIR
    if not raw.is_dir():
        return []
    return sorted(
        path.relative_to(directory).as_posix()
        for path in raw.rglob("*")
        if path.is_file() and not path.name.startswith(".")
    )


def render_page(
    title: str,
    *,
    page_type: str = "",
    tags: Sequence[str] = (),
    sources: Sequence[str] = (),
    summary: str = "",
    body: str = "",
    raw: str = "",
    today: str | None = None,
) -> str:
    """Return a new page with its LLM-wiki header and a first heading."""
    stamp = today or date.today().isoformat()
    day: Any = date.fromisoformat(stamp)  # dumped unquoted, as LLM-wiki writes dates
    header: dict[str, Any] = {}
    if page_type:
        header["type"] = page_type
    header["title"] = title
    header["tags"] = list(tags)
    if page_type != "source":
        header["sources"] = list(sources)
    if summary:
        header["summary"] = summary
    if raw:
        header["raw"] = raw
        header["ingested"] = day
    header["created"] = day
    header["updated"] = day
    head = dump_header(header).strip()
    text = body.strip() or (
        "Write the page here. Link other pages by their name in double square brackets, and "
        "list the source pages it draws from in the header's sources."
    )
    return f"---\n{head}\n---\n# {title}\n\n{text}\n"


def dump_header(header: Mapping[str, Any]) -> str:
    """Return a page header as YAML with inline lists ('tags: [a, b]'), as LLM-wiki reads it."""
    return yaml.dump(
        dict(header), Dumper=_PlainDumper, sort_keys=False, allow_unicode=True,
        default_flow_style=None, width=1000,
    )


class _PlainDumper(yaml.SafeDumper):
    """A safe dumper that writes a repeated value twice instead of '&id001 / *id001'."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def wikilinks(text: str) -> list[str]:
    """Return the page names a text links to with [[name]], [[name|label]], [[name#part]]."""
    return [match.group(1).strip() for match in WIKILINK.finditer(CODE.sub("", text))]


def search(pages: Iterable[Page], query: str) -> list[tuple[Page, int, list[str]]]:
    """Return (page, score, snippets) for pages holding every word of *query*, best first."""
    words = [word.lower() for word in str(query).split() if word.strip()]
    if not words:
        return []
    found: list[tuple[Page, int, list[str]]] = []
    for page in pages:
        title, tags = page.title.lower(), " ".join(page.tags).lower()
        haystack = " ".join([title, tags, page.summary.lower(), page.slug, page.type,
                             page.body.lower()])
        if not all(word in haystack for word in words):
            continue
        score = sum(
            5 * (word in title) + 3 * (word in tags) + 2 * (word in page.summary.lower())
            + page.body.lower().count(word)
            for word in words
        )
        snippets = [
            line.strip()[:160]
            for line in page.body.splitlines()
            if any(word in line.lower() for word in words) and line.strip()
        ][:SNIPPETS]
        found.append((page, score, snippets))
    return sorted(found, key=lambda item: (-item[1], item[0].slug, item[0].language))


def _link_name(page: Page, duplicated: set[str]) -> str:
    return page.slug if page.name.casefold() in duplicated else page.name


def _type_heading(page_type: str) -> str:
    folder = TYPE_DIRS.get(page_type, "")
    return (folder or "pages").capitalize() if page_type else "Pages"


def render_index(pages: Sequence[Page], scope: str, languages: Sequence[str]) -> str:
    """Return index.md: every page as a [[wikilink]] with its summary, grouped by type."""
    grouped: dict[str, list[Page]] = {}
    for page in pages:
        grouped.setdefault(page.slug, []).append(page)
    names: dict[str, int] = {}
    for versions in grouped.values():
        key = versions[0].name.casefold()
        names[key] = names.get(key, 0) + 1
    duplicated = {name for name, count in names.items() if count > 1}
    sections: dict[str, list[str]] = {}
    for _slug, versions in sorted(grouped.items()):
        first = next((page for page in versions if not page.path.stem.count(".")), versions[0])
        languages_here = ", ".join(
            page.language if page is first else f"[[{page.path.stem}|{page.language}]]"
            for page in versions
        )
        summary = first.summary or first.title
        line = f"- [[{_link_name(first, duplicated)}]] - {summary} ({languages_here})"
        sections.setdefault(_type_heading(first.type), []).append(line)
    order = [_type_heading(key) for key in TYPE_DIRS] + ["Pages"]
    lines = [
        INDEX_MARKER,
        f"# Wiki index ({scope})",
        "",
        f"{len(grouped)} pages; languages: {', '.join(languages)}. Read this first, then the "
        "pages it points to. Conventions: SCHEMA.md; history: log.md.",
    ]
    for heading in sorted(sections, key=lambda item: (order.index(item)
                                                       if item in order else len(order), item)):
        lines += ["", f"## {heading}", "", *sections[heading]]
    return "\n".join(lines) + "\n"


def append_log(directory: Path, operation: str, description: str, *,
               today: str | None = None) -> str:
    """Append one '## [date] op | description' entry to log.md (created on first use)."""
    path = directory / LOG_NAME
    entry = (f"## [{today or date.today().isoformat()}] {operation.strip() or 'note'} | "
             f"{' '.join(description.split())}")
    existing = path.read_text(encoding="utf-8") if path.is_file() else (
        "# Wiki Log\n\nAppend-only chronological record of operations on this wiki. Each "
        "entry begins with `## [YYYY-MM-DD] <op> | <description>` so it is parseable with "
        "`grep \"^## \\[\" log.md | tail -N`.\n\n---\n"
    )
    joined = existing if existing.endswith("\n") else existing + "\n"
    directory.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"{joined}\n{entry}\n")
    return entry


def read_log(directory: Path, limit: int = 20) -> list[dict[str, str]]:
    """Return the newest *limit* log entries, oldest first."""
    path = directory / LOG_NAME
    if not path.is_file():
        return []
    entries = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = LOG_ENTRY.match(line)
        if match:
            entries.append({"date": match[1], "operation": match[2], "description": match[3]})
    return entries[-max(1, limit):]


def schema_text(scope: str, languages: Sequence[str], default_language: str) -> str:
    """Return the starting SCHEMA.md of a wiki: the contract an agent reads first."""
    others = [language for language in languages if language != default_language]
    suffixes = ", ".join(f"`page.{language}.md`" for language in others) or "none yet"
    types = "\n".join(f"- `{kind}` in `{folder}/`" for kind, folder in TYPE_DIRS.items())
    types += "\n- `page` - anything else, at the wiki root (`home.md`, an overview)"
    return f"""# Wiki Schema ({scope})

The conventions of this wiki. Read this first; its rules override general habits. It follows
the LLM-wiki pattern (raw sources, a maintained wiki, this schema), so it can be merged with
another LLM-wiki or opened as an Obsidian vault. Edit this file as the wiki evolves.

## Layout

- `raw/` - immutable sources: articles, PDFs, transcripts, notes. Read them, never edit them.
  Add one with `kdx wiki ingest FILE`.
- Pages, by type:
{types}
- `index.md` - generated catalog (`kdx wiki index`); `log.md` - append-only history.

## Pages

Every page starts with a YAML header: `type`, `title`, `tags`, `sources` (the source-page
names it draws from), `summary`, `created`, `updated`; a source page has `raw` and `ingested`
instead of `sources`. Link pages as `[[page-name]]` (the file name without `.md` and without a
language suffix). One page is about one thing; split beyond {SOFT_LINES} lines, never exceed
{HARD_LINES}.

## Languages

The default language is `{default_language}`: `page.md`. Other languages: {suffixes}. A page
should exist in every listed language; `kdx wiki check` reports the missing ones.

## Operations

- ingest: `kdx wiki ingest FILE`, then write the source page's summary, update the pages it
  touches, `kdx wiki index`, and record it: `kdx wiki log update "..."`.
- query: read `index.md`, then the pages; file a good answer back as a `synthesis` page.
- lint: `kdx wiki check` (links, sources, orphans, translations, size); fix, then log it.

Every change is one line in `log.md`: `## [YYYY-MM-DD] <op> | <description>`.
"""


def _resolver(pages: Sequence[Page]) -> dict[str, list[Page]]:
    names: dict[str, list[Page]] = {}
    for page in pages:
        for key in {page.name, page.slug, page.path.stem}:
            names.setdefault(key.casefold(), []).append(page)
    return names


def check_pages(
    pages: Sequence[Page],
    languages: Sequence[str],
    *,
    directory: Path | None = None,
    index_current: bool = True,
) -> list[Issue]:
    """Return what is wrong with a wiki, the way an LLM-wiki lint pass would see it.

    Errors: broken links and wikilinks, a source name that is no page, a missing raw file.
    Warnings: header problems, orphans, sourced types without sources, missing translations,
    oversized pages, duplicate names, raw files no source page names, a stale index.
    """
    issues: list[Issue] = []
    names = _resolver(pages)
    inbound: dict[str, int] = {}
    referenced_raw: set[str] = set()
    for page in pages:
        where = str(page.path)
        issues.extend(Issue("warning", where, problem) for problem in page.problems)
        prose = CODE.sub("", page.body)
        for target, _anchor in LINK.findall(prose):
            resolved = (page.path.parent / target).resolve()
            if target.endswith(".md") and not resolved.exists():
                issues.append(Issue("error", where, f"broken link to {target}"))
            elif target.endswith(".md"):
                stem = Path(target).name[: -len(".md")].casefold()
                for other in names.get(stem, []):
                    if other.slug != page.slug:
                        inbound[other.slug] = inbound.get(other.slug, 0) + 1
        for name in wikilinks(page.body):
            found = names.get(name.casefold())
            if not found:
                issues.append(Issue("error", where, f"broken wikilink [[{name}]]"))
                continue
            for linked in {item.slug for item in found} - {page.slug}:
                inbound[linked] = inbound.get(linked, 0) + 1
        for source in page.sources:
            found = names.get(source.casefold())
            if not found:
                issues.append(Issue("error", where, f"source {source!r} is not a page"))
            for cited in {item.slug for item in found or []} - {page.slug}:
                inbound[cited] = inbound.get(cited, 0) + 1
        if not page.type:
            issues.append(Issue("warning", where, "no 'type' in the header"))
        if not page.tags:
            issues.append(Issue("warning", where, "no tags"))
        if page.type in SOURCED_TYPES and not page.sources:
            issues.append(Issue("warning", where, f"a {page.type} page lists no sources"))
        if page.raw:
            referenced_raw.add(page.raw)
            if directory is not None and not (directory / page.raw).is_file():
                issues.append(Issue("error", where, f"raw file {page.raw} is missing"))
        lines = page.body.count("\n") + 1
        if lines > HARD_LINES:
            issues.append(Issue("warning", where, f"{lines} lines: split it (limit {HARD_LINES})"))
    by_slug: dict[str, set[str]] = {}
    first_name: dict[str, str] = {}
    source_pages = {page.slug for page in pages if page.type == "source"}
    for page in pages:
        by_slug.setdefault(page.slug, set()).add(page.language)
        first_name.setdefault(page.slug, page.name)
    seen_names: dict[str, list[str]] = {}
    for slug, name in first_name.items():
        seen_names.setdefault(name.casefold(), []).append(slug)
    for name, slugs in sorted(seen_names.items()):
        if len(slugs) > 1:
            issues.append(Issue("warning", ", ".join(sorted(slugs)),
                                f"two pages are named [[{name}]]; link them by path"))
    for slug, present in sorted(by_slug.items()):
        if not inbound.get(slug) and first_name[slug].casefold() not in ENTRY_NAMES:
            issues.append(Issue("warning", slug, "orphan: no page links here"))
        if slug in source_pages:
            continue  # a source summary stays in the source's language
        for language in languages:
            if language not in present:
                have = ", ".join(sorted(present))
                issues.append(Issue("warning", slug, f"no {language} version (only {have})"))
    if directory is not None:
        for raw in raw_files(directory):
            if raw not in referenced_raw:
                issues.append(Issue("warning", raw, "raw source not ingested: no page names it"))
    if not index_current:
        issues.append(Issue("warning", INDEX_NAME, "the index is stale; run 'kdx wiki index'"))
    return issues


def header_of(text: str) -> Mapping[str, Any]:
    """Return the parsed YAML header of a page text (empty when it has none)."""
    return _header(text)[0]
